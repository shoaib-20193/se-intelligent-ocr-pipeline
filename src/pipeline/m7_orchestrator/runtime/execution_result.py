from dataclasses import dataclass, field
from typing import Dict, Any, List, Optional
from src.pipeline.m7_orchestrator.state.pipeline_state import PipelineState
from src.pipeline.m7_orchestrator.telemetry.pipeline_metrics import PipelineMetrics
from src.pipeline.m5_semantic.contracts import StructuredDocument

@dataclass
class PipelineExecutionResult:
    """
    The final output artifact generated by the M7 Orchestrator.
    """
    document_id: str
    final_state: PipelineState
    structured_document: Optional[StructuredDocument]
    metrics: PipelineMetrics
    failure_summary: List[str] = field(default_factory=list)
    stage_timings: Dict[str, float] = field(default_factory=dict)
    debug_artifacts: Dict[str, str] = field(default_factory=dict)
